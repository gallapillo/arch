#include <stdio.h>
#include <stdlib.h>
#include <fcntl.h>
#include <unistd.h>
#include "myBigChars.h"

// Определение шрифтов для символов 0-9, A-F, +, 1
// Каждый символ - массив из 2 int (64 бита = 8x8 пикселей)
static int font_data[FONT_SIZE][2] = {
    // 0
    {0x7E81818181817E00, 0x0000000000000000},
    // 1
    {0x1030101010107C00, 0x0000000000000000},
    // 2
    {0x7E01017E807E0000, 0x0000000000000000},
    // 3
    {0x7E017E017E000000, 0x0000000000000000},
    // 4
    {0x81817E0101010100, 0x0000000000000000},
    // 5
    {0x7E807E017E000000, 0x0000000000000000},
    // 6
    {0x7E807E817E000000, 0x0000000000000000},
    // 7
    {0x7E01010101010000, 0x0000000000000000},
    // 8
    {0x7E817E817E000000, 0x0000000000000000},
    // 9
    {0x7E817E017E000000, 0x0000000000000000},
    // A (10)
    {0x7E8181FF81810000, 0x0000000000000000},
    // B (11)
    {0xFE81FE81FE000000, 0x0000000000000000},
    // C (12)
    {0x7E818080817E0000, 0x0000000000000000},
    // D (13)
    {0xFC82828282FC0000, 0x0000000000000000},
    // E (14)
    {0xFE80FE80FE000000, 0x0000000000000000},
    // F (15)
    {0xFE80FE8080800000, 0x0000000000000000},
    // + (16)
    {0x00107C1010000000, 0x0000000000000000},
    // 1 (17) - утолщенная единица
    {0x18381818187E0000, 0x0000000000000000}
};

int main(int argc, char *argv[]) {
    const char *filename = "font.bin";
    
    if (argc > 1) {
        filename = argv[1];
    }
    
    int fd = open(filename, O_WRONLY | O_CREAT | O_TRUNC, 0644);
    if (fd == -1) {
        perror("Не удалось создать файл шрифта");
        return 1;
    }
    
    printf("Генерация шрифта в файл: %s\n", filename);
    
    for (int i = 0; i < FONT_SIZE; i++) {
        if (bc_bigcharwrite(fd, font_data[i], 1) == -1) {
            perror("Ошибка записи шрифта");
            close(fd);
            return 1;
        }
    }
    
    close(fd);
    printf("Шрифт успешно сгенерирован (%d символов)\n", FONT_SIZE);
    
    return 0;
}