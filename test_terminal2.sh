#!/bin/bash

# test_terminal2.sh - Скрипт для проверки псевдографических символов

# Определяем escape-последовательности
ENTER_ACS=$(infocmp -1 | grep 'enacs=\\E(B\\E)0' | sed 's/enacs=//')
EXIT_ACS=$(infocmp -1 | grep 'rmacs=\\E(B' | sed 's/rmacs=//')
SMACS=$(infocmp -1 | grep 'smacs=\\E(0' | sed 's/smacs=//')

# Очистка экрана
echo -e "\033[H\033[J"

# Вход в режим псевдографики
echo -e "\033(0"

# Рисуем рамку 8x8 начиная с 10 строки, 5 символа
# Используем псевдографические символы: l=верхний левый, q=горизонталь, 
# k=верхний правый, x=вертикаль, m=нижний левый, j=нижний правый

# Верхняя граница
echo -e "\033[10;5Hlqqqqqqqk"

# Боковые границы и внутренность
for i in {1..6}; do
    row=$((10 + i))
    echo -e "\033[${row};5Hx       x"
done

# Нижняя граница
echo -e "\033[17;5Hmqqqqqqqj"

# Выводим закрашенный прямоугольник (ACS_CKBOARD) в виде цифры (день рождения 3)
# Цифра 3 из закрашенных блоков (примерная форма)
echo -e "\033[12;7Hhhhhhhh"
echo -e "\033[13;7Hhhhhhhh"
echo -e "\033[14;7Hhhhhhhh"
echo -e "\033[15;14Hhhhhhhh"
echo -e "\033[16;14Hhhhhhhh"

# Выход из режима псевдографики
echo -e "\033(B"

# Возврат курсора
echo -e "\033[20;1H"
echo "=== Проверка псевдографики завершена ==="